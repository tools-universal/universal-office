/** .pptx com os textos traduzidos para o inglês. */
export function translatePptx(bytes) {
  const z = unzipSync(bytes);
  for (const k of Object.keys(z)) {
    if (!/^ppt\/(slides|charts|diagrams|notesSlides)\/[^/]+\.xml$/.test(k)) continue;
    z[k] = strToU8(strFromU8(z[k]).replace(/<(a:t|c:v)>([^<]*)<\/\1>/g, (m, tag, text) => (text in EN ? `<${tag}>${EN[text]}</${tag}>` : m)));
  }
  return zipSync(z);
}
